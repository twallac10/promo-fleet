#!/usr/bin/env bash
# Generate clusters/<tier>/apps.yaml from apps.yaml: per app, a GitRepository
# for its repo and a Kustomization syncing ./tiers/<tier>.
# OUT_DIR overrides the output root (tests compare against the committed files).
set -euo pipefail
cd "$(dirname "$0")/.."
out=${OUT_DIR:-clusters}
for t in $(yq '.tiers[].name' tiers.yaml); do
  mkdir -p "$out/$t"
  {
    echo "# GENERATED by scripts/gen-clusters.sh from apps.yaml. Do not edit."
    first=1
    for app in $(yq '.apps[].name' apps.yaml); do
      [ $first = 1 ] || echo "---"; first=0
      APP=$app TIER=$t yq -n '
        .apiVersion = "source.toolkit.fluxcd.io/v1" | .kind = "GitRepository" |
        .metadata = {"name": "app-" + strenv(APP), "namespace": "flux-system"} |
        .spec = {"interval": "1m", "url": "https://github.com/twallac10/promo-" + strenv(APP), "ref": {"branch": "main"}}'
      echo "---"
      deps=$(yq -o json -I0 ".apps[] | select(.name==\"$app\") | .dependsOn" apps.yaml)
      APP=$app TIER=$t DEPS=$deps yq -n '
        .apiVersion = "kustomize.toolkit.fluxcd.io/v1" | .kind = "Kustomization" |
        .metadata = {"name": "app-" + strenv(APP), "namespace": "flux-system"} |
        .spec.interval = "10m" |
        .spec.path = "./tiers/" + strenv(TIER) |
        .spec.prune = true |
        .spec.wait = true |
        .spec.timeout = "10m" |
        .spec.sourceRef = {"kind": "GitRepository", "name": "app-" + strenv(APP)} |
        .spec.dependsOn = (env(DEPS) | map({"name": (select(. == "canary" or . == "guardrails" or . == "testkube") // ("app-" + .))})) |
        with(select(.spec.dependsOn | length == 0); del(.spec.dependsOn))'
    done
  } > "$out/$t/apps.yaml"
done
